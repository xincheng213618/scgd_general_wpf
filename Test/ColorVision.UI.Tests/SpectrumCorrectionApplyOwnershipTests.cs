namespace ColorVision.UI.Tests;

public sealed class SpectrumCorrectionApplyOwnershipTests
{
    [Theory]
    [InlineData("remote")]
    [InlineData("local")]
    [InlineData("local auto ND")]
    [InlineData("local busy")]
    [InlineData("retired")]
    [InlineData("changed source path")]
    [InlineData("changed source bytes")]
    [InlineData("changed generated bytes")]
    [InlineData("changed persisted selection")]
    [InlineData("database failure")]
    public async Task WindowAppliesOnlyItsCapturedDeviceAndFileVersions(string scenario)
    {
        DirectoryInfo directory = Directory.CreateTempSubdirectory("cv-spectrum-correction-apply-");
        try
        {
            string originalDb = Path.Combine(directory.FullName, "original.db");
            string replacementDb = Path.Combine(directory.FullName, "replacement.db");
            string source = NewMagnitudeFile(directory, "source.dat", 1, out string sourceHash);
            string generated = NewMagnitudeFile(directory, "generated.dat", 2, out string generatedHash);
            string alternatePath = Path.Combine(directory.FullName, "alternate.dat");
            File.Copy(source, alternatePath);
            var config = new ConfigSpectrum { Code = "spectrum-correction", SN = "SN1", WavelengthFile = "wave.dat", MaguideFile = source };
            config.EnsureCalibrationGroups();
            JObject persisted = JObject.FromObject(config);
            persisted["Unrelated"] = 17;
            persisted["CalibrationGroups"]![0]!["UnrelatedGroupProperty"] = "preserve";

            using var firstDb = Open(originalDb);
            using var secondDb = Open(replacementDb);
            SysResourceModel originalRow = Seed(firstDb, config.Code, persisted.ToString());
            persisted["Unrelated"] = 42;
            SysResourceModel replacementRow = Seed(secondDb, config.Code, persisted.ToString());
            Assert.Equal(originalRow.Id, replacementRow.Id);

            MySqlConnectedEndpoint? active = null;
            int secondOpens = 0;
            var firstEndpoint = new MySqlConnectedEndpoint(endpoint => ReferenceEquals(endpoint, active), () => Open(originalDb));
            var secondEndpoint = new MySqlConnectedEndpoint(endpoint => ReferenceEquals(endpoint, active), () =>
            {
                secondOpens++;
                return Open(replacementDb);
            });
            active = firstEndpoint;
            DeviceSpectrum owner = NewSpectrum(originalRow, config, firstEndpoint, scenario is "local" or "local auto ND" or "local busy");
            string? actualWavelength = scenario == "local auto ND" ? Path.Combine(directory.FullName, "active-nd-wave.dat") : null;
            var measurement = new SpectrumMeasurementSnapshot(1, config.Code, config.SN, DateTimeOffset.Now, 380, 780,
                0.1, [1, 2], 1, 1, 10, 1, "Luminance", config.ActiveCalibrationGroupName, source, sourceHash)
            {
                SourceWavelengthPath = actualWavelength
            };
            var host = owner.CreateSpectrumCorrectionHost(_ =>
            {
                if (actualWavelength != null)
                {
                    config.WavelengthFile = actualWavelength;
                    JObject autoNdConfiguration = JObject.Parse(originalRow.Value!);
                    autoNdConfiguration["WavelengthFile"] = actualWavelength;
                    string changedJson = autoNdConfiguration.ToString();
                    firstDb.Updateable<SysResourceModel>().SetColumns(row => row.Value == changedJson)
                        .Where(row => row.Id == originalRow.Id).ExecuteCommand();
                }
                return Task.FromResult(measurement);
            });
            Assert.Same(measurement, await host.CaptureAsync(CancellationToken.None));

            switch (scenario)
            {
                case "retired":
                    active = secondEndpoint;
                    owner.ResultDatabaseEndpoint = secondEndpoint;
                    break;
                case "changed source path":
                    config.MaguideFile = alternatePath;
                    break;
                case "changed source bytes":
                    File.Copy(generated, source, true);
                    break;
                case "changed generated bytes":
                    File.Copy(source, generated, true);
                    break;
                case "changed persisted selection":
                    persisted["MaguideFile"] = alternatePath;
                    string changedJson = persisted.ToString();
                    firstDb.Updateable<SysResourceModel>().SetColumns(row => row.Value == changedJson)
                        .Where(row => row.Id == originalRow.Id).ExecuteCommand();
                    break;
                case "database failure":
                    firstDb.Ado.ExecuteCommand("CREATE TRIGGER reject_correction BEFORE UPDATE ON t_scgd_sys_resource " +
                        "BEGIN SELECT RAISE(ABORT, 'synthetic correction failure'); END");
                    break;
            }

            string priorVersion = firstDb.Queryable<SysResourceModel>().InSingle(originalRow.Id).Value!;
            string livePath = config.MaguideFile;
            var request = new SpectrumCorrectionApplyRequest(generated, measurement.CalibrationGroupName, sourceHash)
            {
                ExpectedGeneratedMagnitudeSha256 = generatedHash
            };
            bool localBusy = scenario == "local busy";
            if (localBusy) owner.SpectrumBackend.BeginLocalCommand();
            SpectrumCorrectionApplyResult result;
            try { result = await host.ApplyMagnitudeFileAsync(request, CancellationToken.None); }
            finally { if (localBusy) owner.SpectrumBackend.EndLocalCommand(); }

            bool accepted = scenario is "remote" or "local" or "local auto ND";
            Assert.Equal(accepted, result.IsAccepted);
            Assert.Equal(accepted ? generated : livePath, config.MaguideFile);
            Assert.Equal(config.MaguideFile, config.ActiveCalibrationGroup.MaguideFile);
            string finalVersion = firstDb.Queryable<SysResourceModel>().InSingle(originalRow.Id).Value!;
            if (accepted)
            {
                var saved = JObject.Parse(finalVersion);
                Assert.Equal(generated, (string?)saved["MaguideFile"]);
                Assert.Equal(generated, (string?)saved["CalibrationGroups"]![0]!["MaguideFile"]);
                Assert.Equal(17, (int?)saved["Unrelated"]);
                Assert.Equal("preserve", (string?)saved["CalibrationGroups"]![0]!["UnrelatedGroupProperty"]);
                Assert.Equal(SpectrumCorrectionApplyStatus.Succeeded, result.Status);
            }
            else Assert.Equal(priorVersion, finalVersion);
            Assert.Equal(replacementRow.Value, secondDb.Queryable<SysResourceModel>().InSingle(replacementRow.Id).Value);
            Assert.Equal(0, secondOpens);
        }
        finally
        {
            foreach (FileInfo file in directory.EnumerateFiles()) file.Delete();
            directory.Delete();
        }
    }

    private static DeviceSpectrum NewSpectrum(SysResourceModel resource, ConfigSpectrum config,
        MySqlConnectedEndpoint endpoint, bool local)
    {
        var device = (DeviceSpectrum)RuntimeHelpers.GetUninitializedObject(typeof(DeviceSpectrum));
        device.SysResourceModel = resource;
        device.Config = config;
        device.ResultDatabaseEndpoint = endpoint;
        var backend = new SpectrumBackendState(local);
        if (local) backend.SetLocalStatus(DeviceStatusType.Opened);
        else backend.ObserveService(DeviceStatusType.Opened);
        SetField(device, "<SpectrumBackend>k__BackingField", backend);
        SetField(device, "<CalibrationGroupChangeGuard>k__BackingField", new SpectrumCalibrationGroupChangeGuard());
        SetField(device, "correctionMeasurementGate", new SemaphoreSlim(1, 1));
        device.DService = (MQTTSpectrum)RuntimeHelpers.GetUninitializedObject(typeof(MQTTSpectrum));
        device.DService.Device = device;
        return device;
    }

    private static void SetField(DeviceSpectrum device, string name, object value) =>
        typeof(DeviceSpectrum).GetField(name, BindingFlags.Instance | BindingFlags.NonPublic)!.SetValue(device, value);

    private static string NewMagnitudeFile(DirectoryInfo directory, string name, double coefficient, out string sha256)
    {
        double[] wavelengths = Enumerable.Range(0, 4001).Select(index => 380 + 0.1 * index).ToArray();
        return MagnitudeCalibrationFile.Create(4, 683, wavelengths, Enumerable.Repeat(coefficient, wavelengths.Length).ToArray())
            .SaveNew(Path.Combine(directory.FullName, name), out sha256);
    }

    private static SysResourceModel Seed(SqlSugarClient db, string code, string json)
    {
        db.CodeFirst.InitTables<SysResourceModel>();
        // A missing parent allows normal remote persistence while keeping this test offline.
        var resource = new SysResourceModel { Code = code, Name = "Spectrum", Type = (int)ServiceTypes.Spectrum, Value = json };
        resource.Id = db.Insertable(resource).ExecuteReturnIdentity();
        return resource;
    }

    private static SqlSugarClient Open(string path) => new(new ConnectionConfig
    {
        ConnectionString = $"Data Source={path};Pooling=False", DbType = DbType.Sqlite,
        InitKeyType = InitKeyType.Attribute, IsAutoCloseConnection = true
    });
}
