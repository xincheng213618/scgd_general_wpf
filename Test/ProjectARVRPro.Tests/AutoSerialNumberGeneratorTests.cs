using Xunit;

namespace ProjectARVRPro.Tests
{
    public class AutoSerialNumberGeneratorTests
    {
        [Fact]
        public void FormatUsesRecognizableTimestampRule()
        {
            DateTime timestamp = new(2026, 7, 25, 19, 30, 45, 123);

            string serialNumber = AutoSerialNumberGenerator.Format(timestamp);

            Assert.Equal("AUTO60725193045", serialNumber);
            Assert.True(AutoSerialNumberGenerator.IsAutoGenerated(serialNumber));
        }

        [Fact]
        public void CreateReturnsDistinctRuleBasedValues()
        {
            string first = AutoSerialNumberGenerator.Create();
            string second = AutoSerialNumberGenerator.Create();

            Assert.NotEqual(first, second);
            Assert.True(AutoSerialNumberGenerator.IsAutoGenerated(first));
            Assert.True(AutoSerialNumberGenerator.IsAutoGenerated(second));
        }

        [Theory]
        [InlineData(null)]
        [InlineData("")]
        [InlineData("G1048")]
        [InlineData("AUTO0725193045")]
        public void IsAutoGeneratedRejectsValuesOutsideTheRule(string? serialNumber)
        {
            Assert.False(AutoSerialNumberGenerator.IsAutoGenerated(serialNumber));
        }
    }
}
