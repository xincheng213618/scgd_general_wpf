using System.Globalization;

namespace ProjectARVRPro
{
    public static class AutoSerialNumberGenerator
    {
        public const string Prefix = "AUTO";

        private static readonly object SyncRoot = new();
        private static DateTime _lastGeneratedSecond;

        public static string Create()
        {
            lock (SyncRoot)
            {
                DateTime now = DateTime.Now;
                DateTime timestamp = new(now.Year, now.Month, now.Day, now.Hour, now.Minute, now.Second, now.Kind);
                if (timestamp <= _lastGeneratedSecond)
                {
                    timestamp = _lastGeneratedSecond.AddSeconds(1);
                }

                _lastGeneratedSecond = timestamp;
                return Format(timestamp);
            }
        }

        public static string Format(DateTime timestamp)
        {
            return $"{Prefix}{timestamp.Year % 10}{timestamp.ToString("MMddHHmmss", CultureInfo.InvariantCulture)}";
        }

        public static bool IsAutoGenerated(string? serialNumber)
        {
            return serialNumber is { Length: 15 }
                && serialNumber.StartsWith(Prefix, StringComparison.Ordinal)
                && serialNumber.AsSpan(Prefix.Length).IndexOfAnyExceptInRange('0', '9') < 0;
        }
    }
}
